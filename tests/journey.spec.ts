test('mobile gallery closes back to stop details and resets for the next stop', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/day/04')
  await page.getByRole('button', { name: 'Open stop 2: Nanda Devi Temple', exact: true }).click()
  const stop = page.getByRole('dialog', { name: 'Nanda Devi Temple', exact: true })
  const opener = stop.getByRole('button', { name: 'Open Nanda Devi Temple photo gallery' })
  await opener.click()
  const viewer = page.getByRole('dialog', { name: 'Nanda Devi Temple photo gallery', exact: true })
  const box = await viewer.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  expect(box!.y + box!.height).toBeLessThanOrEqual(844)
  await viewer.locator('.gallery-viewer-stage').evaluate((element) => {
    const start = new Touch({ identifier: 1, target: element, clientX: 300, clientY: 250 })
    const end = new Touch({ identifier: 1, target: element, clientX: 100, clientY: 252 })
    element.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [start] }))
    element.dispatchEvent(new TouchEvent('touchend', { bubbles: true, changedTouches: [end] }))
  })
  await expect(viewer.locator('.gallery-caption')).toContainText('2 / 3')
  await page.keyboard.press('Escape')
  await expect(viewer).not.toBeVisible()
  await expect(stop).toBeVisible()
  await expect(opener).toBeFocused()
  await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
  await stop.getByRole('button', { name: 'Next stop', exact: true }).click()
  const nextStop = page.getByRole('dialog', { name: 'Balati Bend trailhead', exact: true })
  await expect(nextStop.locator('.gallery-toolbar')).toContainText('1 / 2')
  await expect(nextStop.locator('.gallery-reference')).toContainText('not the trailhead gate')
  await page.keyboard.press('Escape')
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
})

